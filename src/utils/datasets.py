"""
src/utils/datasets.py
───────────────────────────────────────────────────────────────────────────────
PyTorch Dataset wrappers for Tasks 1-3 (Oxford-IIIT Pet) and Task 4 (FS2K).

Key design decisions:
  • Images are cached as uint8 NumPy arrays (128×128×3) on Google Drive.
    Loading from cache is ~10× faster than re-decoding JPEG on Colab's
    limited CPUs (typically 2 vCPUs).
  • Corruption is applied in __getitem__, never to disk – spec §"Runtime
    corruption".
  • Val/test corruptions are deterministic: records are loaded from the
    manifests generated by corruption.generate_val_manifest /
    generate_test_manifest.
  • Balanced batch sampler for Task 2 classifier (WeightedRandomSampler).
"""

import json
from pathlib import Path
from typing import Callable, Dict, List, Optional, Tuple

import numpy as np
import torch
from PIL import Image
from torch.utils.data import Dataset, WeightedRandomSampler

from src.utils.corruption import (
    LABEL_TO_IDX,
    corrupt_from_record,
    corrupt_random,
)


# ── Oxford-IIIT Pet (Tasks 1-3) ───────────────────────────────────────────────

class PetDataset(Dataset):
    """
    Dataset for Oxford-IIIT Pet images (Tasks 1-3).

    In *train* mode  – corruption is sampled randomly each call (new type &
    severity every __getitem__).
    In *eval* mode   – corruption is loaded from a pre-generated manifest
    (deterministic).

    Args:
        cache_paths:  list of paths to cached uint8 .npy files (128×128×3).
        manifest:     list of records from val/test manifest JSON.  If None,
                      the dataset is in training mode.
        transform:    optional callable applied to the clean target tensor
                      (e.g., normalisation).  Applied after [0,1] scaling.
        seed:         base seed for the training-mode RNG.  Each sample
                      uses seed + sample_index so corruption is reproducible
                      across epochs when deterministic=True.
        deterministic: if True and in training mode, use a fixed seed per
                      index (useful for debugging, not for training).
    """

    def __init__(
        self,
        cache_paths: List[str],
        manifest: Optional[List[dict]] = None,
        transform: Optional[Callable] = None,
        seed: int = 0,
        deterministic: bool = False,
    ):
        self.cache_paths   = [str(p) for p in cache_paths]
        self.manifest      = manifest
        self.transform     = transform
        self.seed          = seed
        self.deterministic = deterministic
        self.training_mode = manifest is None

        if not self.training_mode:
            # Index manifest by image path for O(1) lookup
            self._records: List[dict] = manifest  # type: ignore[assignment]

    def __len__(self) -> int:
        if self.training_mode:
            return len(self.cache_paths)
        return len(self._records)

    def __getitem__(self, idx: int) -> Tuple[torch.Tensor, torch.Tensor, int]:
        """
        Returns:
            (corrupted, clean, label_idx)
            • corrupted, clean: float32 tensors in [0,1], shape (3, H, W).
            • label_idx: integer in {0,1,2,3} → LABEL_TO_IDX.
        """
        if self.training_mode:
            img    = np.load(self.cache_paths[idx])         # uint8 (H,W,3)
            rng    = (np.random.default_rng(self.seed + idx)
                      if self.deterministic
                      else np.random.default_rng())
            corrupted, corruption, _ = corrupt_random(img, rng)
            label  = LABEL_TO_IDX[corruption]
        else:
            record     = self._records[idx]
            raw_path   = record["image_path"].replace(".jpg", ".npy").replace(".png", ".npy")
            img_path   = Path(raw_path)
            if not img_path.exists():
                fname = img_path.name
                found = False
                if self.cache_paths:
                    candidate = Path(self.cache_paths[0]).parent / fname
                    if candidate.exists():
                        img_path = candidate
                        found = True
                if not found:
                    for c_dir in [
                        Path("/content/drive/MyDrive/genai_assignment/data/pets_cache/val"),
                        Path("/content/drive/MyDrive/genai_assignment/data/pets_cache/test"),
                        Path("/content/drive/MyDrive/genai_assignment/data/pets_cache/train"),
                        Path("data/pets_cache/val"),
                        Path("data/pets_cache/test"),
                        Path("data/pets_cache/train"),
                    ]:
                        if (c_dir / fname).exists():
                            img_path = c_dir / fname
                            break
            img        = np.load(str(img_path))
            corrupted  = corrupt_from_record(img, record)
            label      = LABEL_TO_IDX[record["corruption_type"]]

        clean_t     = _to_tensor(img)
        corrupted_t = _to_tensor(corrupted)

        if self.transform is not None:
            clean_t     = self.transform(clean_t)
            corrupted_t = self.transform(corrupted_t)

        return corrupted_t, clean_t, label


def make_balanced_sampler(labels: List[int], num_classes: int = 4) -> WeightedRandomSampler:
    """
    WeightedRandomSampler that enforces class-balanced batches.

    Each sample is assigned weight = 1 / class_count, so under-represented
    classes are up-sampled to equality.

    Used for Task 2 classifier training (spec: "class-balanced batches").

    Reference: PyTorch docs §torch.utils.data.WeightedRandomSampler.
    """
    counts  = np.bincount(labels, minlength=num_classes).astype(float)
    counts  = np.where(counts == 0, 1.0, counts)      # avoid div-by-zero
    weights = 1.0 / counts
    sample_weights = torch.tensor([weights[l] for l in labels], dtype=torch.float64)
    return WeightedRandomSampler(
        weights=sample_weights,
        num_samples=len(sample_weights),
        replacement=True,
    )


# ── FS2K (Task 4) ─────────────────────────────────────────────────────────────

class FS2KDataset(Dataset):
    """
    Dataset for the FS2K Facial Sketch Synthesis dataset (Task 4).

    Each sample is a (photo, sketch, style_label) triple.  Spatial
    augmentation is applied identically to both images to preserve the
    pixel-level correspondence required for paired GAN training.

    Reference: FS2K – Fan et al. (2022) "Face Photo-Sketch Synthesis
    and Recognition", arXiv:2201.01032.

    Args:
        pairs:        list of {"photo": path, "sketch": path, "style": int}.
        augment:      if True, apply horizontal flip with p=0.5 (same coin
                      for both photo and sketch).
        cache_dir:    directory containing .npy cached arrays (optional).
    """

    def __init__(
        self,
        pairs: List[Dict],
        augment: bool = False,
        cache_dir: Optional[str] = None,
    ):
        self.pairs     = pairs
        self.augment   = augment
        self.cache_dir = Path(cache_dir) if cache_dir else None

    def __len__(self) -> int:
        return len(self.pairs)

    def __getitem__(self, idx: int) -> Tuple[torch.Tensor, torch.Tensor, int]:
        """
        Returns:
            (photo_t, sketch_t, style_label)
            • photo_t:  float32 (3, 128, 128)  in [-1, 1]  (tanh output range)
            • sketch_t: float32 (1, 128, 128)  in [-1, 1]
            • style_label: int in {0, 1, 2}
        """
        pair        = self.pairs[idx]
        photo_arr   = _load_or_cache(pair["photo"],  self.cache_dir, channels=3)
        sketch_arr  = _load_or_cache(pair["sketch"], self.cache_dir, channels=1)

        # Identical spatial augmentation
        if self.augment and np.random.random() < 0.5:
            photo_arr  = np.fliplr(photo_arr).copy()
            sketch_arr = np.fliplr(sketch_arr).copy()

        # Scale to [-1, 1] (tanh-compatible)
        photo_t  = (_to_tensor(photo_arr)  * 2.0) - 1.0
        sketch_t = (_to_tensor(sketch_arr) * 2.0) - 1.0
        if sketch_t.shape[0] == 3:          # grayscale via mean
            sketch_t = sketch_t.mean(dim=0, keepdim=True)

        return photo_t, sketch_t, int(pair["style"])


# ── Utilities ─────────────────────────────────────────────────────────────────

def _to_tensor(arr: np.ndarray) -> torch.Tensor:
    """uint8 HWC → float32 CHW in [0,1]."""
    if arr.ndim == 2:
        arr = arr[:, :, np.newaxis]
    return torch.from_numpy(arr).permute(2, 0, 1).float() / 255.0


def _load_or_cache(
    path: str,
    cache_dir: Optional[Path],
    channels: int = 3,
) -> np.ndarray:
    """Load image from cache .npy if available, else from raw file."""
    if cache_dir is not None:
        npy_path = cache_dir / (Path(path).stem + ".npy")
        if npy_path.exists():
            return np.load(str(npy_path))

    img = Image.open(path).convert("RGB" if channels == 3 else "L")
    img = img.resize((128, 128), Image.BILINEAR)
    return np.array(img, dtype=np.uint8)


def cache_dataset(
    image_paths: List[str],
    cache_dir: str,
    image_size: int = 128,
) -> List[str]:
    """
    Resize images to (image_size × image_size) RGB uint8 and cache as .npy.

    Returns list of .npy paths in the same order as image_paths.
    Called once from prepare_pets.py – subsequent Colab sessions just load
    from the cache without re-downloading or re-processing.
    """
    from tqdm.auto import tqdm
    out_dir = Path(cache_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    npy_paths: List[str] = []

    for p in tqdm(image_paths, desc="Caching images"):
        stem     = Path(p).stem
        out_path = out_dir / f"{stem}.npy"
        if not out_path.exists():
            img = Image.open(p).convert("RGB")
            img = img.resize((image_size, image_size), Image.BILINEAR)
            np.save(str(out_path), np.array(img, dtype=np.uint8))
        npy_paths.append(str(out_path))

    print(f"[cache_dataset] {len(npy_paths)} images cached in {cache_dir}")
    return npy_paths
